# function = a block of code which is executed only when it is called!
# creating and defining a function! 
def hello(first_name, last_name, age): # parameters
    print("Hello " + first_name + " " + last_name)
    print("You are " + str(age) + " years old!")
    print("Have a nice day!")

# this is how to call a function -> function name + parenthesis
hello("Fizaan", "Ali", 17) # arguments
# hello("Ali")

# no. of arguments should be equal to no. of parameters!