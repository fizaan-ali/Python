name = "Fizaan Ali"
print(len(name))
print(name.find("a")) # returns the first index where that substring is found, if not found returns -1
print(name.capitalize()) # makes only first character uppercase all others going to be lowercase
print(name.upper()) # all characters going to be uppercase
print(name.lower()) # all characters going to be lowercase
print(name.isdigit()) # if our string contains only digits e.g. "1234"
print(name.isalpha()) # if our string contains only alphabets (a-z)
print(name.count("a")) # how many times our string contains 'a'
print(name.replace("a", "o")) # replace first one with secodn one
print(name*3) # prints 3 times the string
