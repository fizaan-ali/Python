import math

pi = 3.1415 
x, y, z = 1, 2, 3

print(round(pi)) # rounds the value
print(math.ceil(pi)) # ceiling function 
print(math.floor(pi)) # floor function
print(abs(pi)) # absolute value
print(pow(pi, 2))  # power
print(math.sqrt(pi)) # square root
print(max(x,y,z)) # finds out the max value
print(min(x,y,z)) # finds out the min value
