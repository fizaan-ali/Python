# Multiple assignment -> assign multiple values to multiple variables in one line of code!

name, age, cgpa = "Fizaan", 17, 3.63 # multiple assignment
print("Name:", name) # using comma automatically adds a space between the two values
print("Age:", age) 
print("CGPA:", cgpa)

ans_sem = fizaan_sem = abdullah_sem = ali_sem = 3 # same value assign to multiple variables

